import {readFileSync, writeFileSync} from 'node:fs';
let text = '// Generated by scripts/sync-abi.mjs. Do not edit.\n';
for (const [name, exported] of [['BlackboxMarket', 'BLACKBOX_MARKET_ABI'], ['BlackboxCoin', 'BLACKBOX_COIN_ABI']]) {
  const {abi} = JSON.parse(readFileSync(`contracts/artifacts/contracts/${name}.sol/${name}.json`, 'utf8'));
  text += `export const ${exported} = ${JSON.stringify(abi, null, 2)} as const;\n`;
}
const path = 'frontend/src/lib/abi.generated.ts';
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== text) throw new Error('Generated ABI differs from compiled contracts');
} else writeFileSync(path, text);
